import { cpSync, existsSync, mkdirSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { join, resolve, basename } from 'node:path'
import type { Config } from '../types.js'
import { resolveDir } from './resolve-file.js'
import { processTemplates } from './template-engine.js'

/**
 * Validate that deployDir is safe to rm -rf:
 * 1. Must be named .deploy (not some arbitrary directory)
 * 2. Must be inside projectRoot (prevents deleting /home, /etc, etc.)
 */
function validateDeployDir(deployDir: string, projectRoot: string): void {
  const resolved = resolve(deployDir)
  const resolvedRoot = resolve(projectRoot)

  // Fleet layout: <fleet>/.airstack/deploy/<machine>/<unit> (its project root is the stack dir,
  // so the inside-projectRoot rule below does not apply; the fixed shape keeps rm -rf safe).
  if (/\/\.airstack\/deploy\/[a-z][a-z0-9-]*\/[a-z0-9][a-z0-9_-]*$/.test(resolved)) return

  if (basename(resolved) !== '.deploy') {
    throw new Error(`deployDir must be named .deploy or be .airstack/deploy/<machine>/<unit>, got: ${resolved}`)
  }

  if (!resolved.startsWith(resolvedRoot + '/') && resolved !== resolvedRoot) {
    throw new Error(`deployDir must be inside projectRoot.\n  deployDir: ${resolved}\n  projectRoot: ${resolvedRoot}`)
  }
}

export interface StageOpts {
  projectRoot: string
  sharedPaths: string[]
  config: Config
  deployDir: string
  /** Extra context merged into template rendering (from plugins) */
  extraContext?: Record<string, unknown>
  errors?: string[]
  /** Plugin-contributed entries to include in the stack manifest */
  manifestEntries?: Record<string, string>
}

/**
 * Stage orchestrator — builds the unit's staging dir (.airstack/deploy/<machine>/<unit>/) from:
 *   1. deploy/ base directory (copied as-is)
 *   2. templates: section (rendered .hbs / copied static files)
 *   3. stack manifest at etc/stacks/{projectName}.env
 */
export function stage(opts: StageOpts): void {
  const { projectRoot, sharedPaths, config, deployDir, extraContext, errors, manifestEntries } = opts

  // 1. Validate and clean the staging dir
  validateDeployDir(deployDir, projectRoot)
  rmSync(deployDir, { recursive: true, force: true })
  mkdirSync(deployDir, { recursive: true })

  // 2. Copy deploy/ base into the staging dir (optional — no deploy/ dir is fine)
  // IMPORTANT: deploy/ base only comes from projectRoot, NOT sharedPaths.
  // Shared paths are for templates and plugins, not for the deploy base layer.
  // Each stack controls its own deploy/ directory contents.
  const deployBase = join(projectRoot, 'deploy')
  if (existsSync(deployBase) && statSync(deployBase).isDirectory()) {
    cpSync(deployBase, deployDir, { recursive: true })
  }

  // 3. Process templates: section
  if (config.templates && Object.keys(config.templates).length > 0) {
    const context = extraContext || {
      host: config.host,
      stack: config.stack,
      plugins: config.plugins,
      manifest: manifestEntries || {},
    }
    processTemplates(config.templates, context, projectRoot, sharedPaths, deployDir, errors)
  }

  // 4. Generate stack manifest at <staging>/etc/stacks/{projectName}.env
  // Post-sync promotes this to the VPS at manifest.destination (default /etc/airstack/stacks/).
  const projectName = config.stack.projectName
  const manifestDir = join(deployDir, 'etc', 'stacks')
  mkdirSync(manifestDir, { recursive: true })
  const manifestPath = join(manifestDir, `${projectName}.env`)

  const manifestContent = [
    '# Generated by airstack deploy — DO NOT EDIT',
    ...Object.entries(manifestEntries || {}).map(([k, v]) => `${k}=${v}`),
  ].join('\n') + '\n'
  writeFileSync(manifestPath, manifestContent, 'utf8')
}
