/**
 * Deploy report renderer.
 *
 * After all phases complete (success or failure):
 * 1. Enriches report.data with deploy results (errors, changes, phaseStatus)
 * 2. Pre-renders each plugin's report section template
 * 3. Renders the main report template
 * 4. Writes to destination + .deploy-logs copy
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import Handlebars from 'handlebars'
import * as yaml from 'js-yaml'
import { resolveFileOptional } from './resolve-file.js'
import type { DeployContext } from '../types.js'

const FALLBACK_TEMPLATE = `# 📦 Deploy Report

> ⚠️ Report template not found. Showing raw deploy data.

**📅 Date:** {{date}}
**📂 Project:** {{stack.projectName}}

## 📋 Phase Summary
{{#each phaseStatus}}
- {{this.phase}}: {{#if this.success}}✅{{else}}❌{{/if}} {{this.message}}
{{/each}}

{{#if errors.length}}
## ⚠️ Errors
{{#each errors}}
- [{{this.phase}}] {{#if this.fatal}}🔴 FATAL: {{/if}}{{this.message}}
{{/each}}
{{/if}}

{{#if changes.length}}
## 🔄 Changes
{{#each changes}}
- [{{this.type}}] {{this.name}}: {{this.details}}
{{/each}}
{{/if}}

{{#each pluginReports}}
## {{this.title}}
{{{this.rendered}}}

{{/each}}

---
*Generated by stack-cli*
`

export function renderReport(ctx: DeployContext, logDir?: string): string {
  const { config, report } = ctx

  // 1. Enrich report data with deploy results
  report.data.errors = ctx.errors
  report.data.changes = ctx.changes
  report.data.phaseStatus = ctx.phaseStatus
  const hasFatal = ctx.errors.some(e => e.fatal)
  const hasWarnings = ctx.errors.some(e => !e.fatal)
  report.data.completedPhase = ctx.phase === 'done'
    ? (hasWarnings ? 'completed with warnings' : 'completed')
    : (hasFatal ? `failed at ${ctx.phase}` : `stopped after ${ctx.phase}`)
  report.data.date = new Date().toISOString().split('T')[0]
  report.data.host = config.host
  report.data.stack = config.stack
  report.data.secrets = config.deploy.report.secrets

  // 2. Parse Docker services from staged docker-compose.yml
  const composePath = join(ctx.deployDir, 'docker-compose.yml')
  if (existsSync(composePath)) {
    try {
      const composeContent = readFileSync(composePath, 'utf-8')
      const compose = yaml.load(composeContent) as Record<string, unknown>
      const rawServices = (compose?.services || {}) as Record<string, Record<string, unknown>>

      // Merge container health status if available (from validate phase)
      const serviceHealth = (report.data.serviceHealth || []) as Array<{ name: string; status: string; healthy: boolean }>
      const healthMap = new Map(serviceHealth.map(s => [s.name, s]))

      const dockerServices = Object.entries(rawServices).map(([name, svc]) => {
        const containerName = String(svc.container_name || name)
        const health = healthMap.get(containerName)
        return {
          name,
          containerName,
          image: String(svc.image || '(build)'),
          status: health?.status || '',
          healthy: health?.healthy ?? false,
          statusChecked: !!health,
        }
      })

      // Find env vars that are present but have empty values (debugging aid)
      const emptyVars: string[] = []
      for (const line of composeContent.split('\n')) {
        const m = line.match(/^\s*-\s+([A-Z][A-Z0-9_]*)=\s*$/)
        if (m) emptyVars.push(m[1])
      }

      report.data.dockerServices = dockerServices
      report.data.emptyEnvVars = emptyVars
    } catch {
      // Parse error — skip
    }
  }

  // 3. Pre-render plugin report sections
  const pluginReports = ctx.plugins
    .filter(p => p.report)
    .sort((a, b) => (a.report!.order ?? 50) - (b.report!.order ?? 50))
    .map(p => {
      try {
        const tmpl = Handlebars.compile(p.report!.template, { noEscape: true })
        return {
          name: p.name,
          title: p.report!.title,
          rendered: tmpl(report.data),
        }
      } catch (err) {
        return {
          name: p.name,
          title: p.report!.title,
          rendered: `*Error rendering report section: ${err instanceof Error ? err.message : String(err)}*`,
        }
      }
    })
  report.data.pluginReports = pluginReports

  // 4. Resolve and render the main report template
  const reportTemplatePath = config.deploy.report.template
  const resolved = resolveFileOptional(ctx.projectRoot, ctx.sharedPaths, reportTemplatePath)

  let templateSrc: string
  if (resolved) {
    templateSrc = readFileSync(resolved, 'utf-8')
  } else {
    ctx.errors.push({
      phase: ctx.phase as string,
      message: `Report template not found: ${reportTemplatePath}`,
      fatal: false,
    })
    templateSrc = FALLBACK_TEMPLATE
  }

  const tmpl = Handlebars.compile(templateSrc, { noEscape: true })
  const rendered = tmpl(report.data)

  // 5. Write to destination (restricted perms — report may contain gateway tokens)
  const destination = join(ctx.projectRoot, config.deploy.report.destination)
  mkdirSync(dirname(destination), { recursive: true })
  writeFileSync(destination, rendered, { mode: 0o600 })

  // 6. Write redacted copy to .deploy-logs (strip secrets for safer log retention)
  if (logDir) {
    mkdirSync(logDir, { recursive: true })

    // Re-render with secrets stripped and gateway tokens redacted
    const redactedData = { ...report.data }
    redactedData.secrets = []

    // Redact plugin report sections that contain tokens (64-hex secrets)
    redactedData.pluginReports = pluginReports.map(p => ({
      ...p,
      rendered: p.rendered.replace(/`[a-f0-9]{64}`/g, '`[REDACTED]`'),
    }))

    const redactedRendered = tmpl(redactedData)
    writeFileSync(join(logDir, 'deploy-report.md'), redactedRendered, { mode: 0o600 })
  }

  return destination
}
