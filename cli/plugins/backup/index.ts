// Built-in backup plugin — generates backup config, deploys backup scripts.
//
// Config schema (under plugins.backup in machines/<m>.yaml or airstack.yaml):
//   Simple:
//     destination: backups/
//     retention_days: 30
//     sources: [...]
//   Advanced:
//     destination: backups/
//     retention_days: 30
//     sets:
//       set-name:
//         sources: [...]
//         retain_count: 10

import type { Plugin, DeployContext, PluginCommandContext } from '../../types.js'
import { mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

// ── Config parsing ──────────────────────────────────────────────────────────

interface BackupSet {
  name: string
  sources: string[]
  retentionDays?: number
  retainCount?: number
}

interface BackupConfig {
  destination: string
  retentionDays: number
  sets: BackupSet[]
}

function parseConfig(raw: unknown, installDir: string): BackupConfig | null {
  if (!raw || typeof raw !== 'object') return null
  const obj = raw as Record<string, unknown>

  const rawDest = String(obj.destination || 'backups/')
  const destination = rawDest.startsWith('/') ? rawDest : `${installDir}/${rawDest}`.replace(/\/$/, '')
  const retentionDays = Number(obj.retentionDays || 30)

  const sets: BackupSet[] = []

  if (Array.isArray(obj.sources) && obj.sources.length > 0) {
    sets.push({
      name: 'default',
      sources: (obj.sources as unknown[]).map(String),
      retentionDays,
    })
  } else if (obj.sets && typeof obj.sets === 'object') {
    for (const [name, setRaw] of Object.entries(obj.sets as Record<string, unknown>)) {
      if (!setRaw || typeof setRaw !== 'object') continue
      const setObj = setRaw as Record<string, unknown>
      const sources = Array.isArray(setObj.sources) ? (setObj.sources as unknown[]).map(String) : []
      if (sources.length === 0) continue
      sets.push({
        name,
        sources,
        retentionDays: setObj.retentionDays ? Number(setObj.retentionDays) : retentionDays,
        retainCount: setObj.retainCount ? Number(setObj.retainCount) : undefined,
      })
    }
  }

  if (sets.length === 0) return null

  return { destination, retentionDays, sets }
}

// ── INI config generation ───────────────────────────────────────────────────

function generateIniConfig(config: BackupConfig): string {
  const lines: string[] = [
    '# Generated by airstack backup plugin — DO NOT EDIT',
    `DESTINATION=${config.destination}`,
    `RETENTION_DAYS=${config.retentionDays}`,
    '',
  ]

  for (const set of config.sets) {
    lines.push(`[${set.name}]`)
    for (const source of set.sources) {
      lines.push(`SOURCE=${source}`)
    }
    if (set.retainCount !== undefined) {
      lines.push(`RETAIN_COUNT=${set.retainCount}`)
    } else {
      lines.push(`RETENTION_DAYS=${set.retentionDays || config.retentionDays}`)
    }
    lines.push('')
  }

  return lines.join('\n')
}

// ── Hooks ───────────────────────────────────────────────────────────────────


async function preStageHook(ctx: DeployContext, raw: unknown): Promise<void> {
  const config = parseConfig(raw, ctx.config.stack.installDir)
  if (!config) {
    ctx.log.warn(`[backup] No backups configured for stack '${ctx.config.stack.projectName}'`)
    return
  }

  ctx.manifest.entries.BACKUP_HEALTH_CHECK = `${ctx.config.stack.installDir}/plugins/backup/check-health.sh`

  // Enrich plugins.backup with resolved destination
  const backupPlugin = (ctx.config.plugins.backup || {}) as Record<string, unknown>
  backupPlugin.resolvedDestination = config.destination
  ctx.config.plugins.backup = backupPlugin

  ctx.log.info(`[backup] Registered ${config.sets.length} backup set(s), destination: ${config.destination}`)
}

async function stageHook(ctx: DeployContext, raw: unknown): Promise<void> {
  const config = parseConfig(raw, ctx.config.stack.installDir)
  if (!config) return

  const { deployDir } = ctx

  // 1. Generate backup config
  const configDir = join(deployDir, '.stack-config', 'backup')
  mkdirSync(configDir, { recursive: true })
  writeFileSync(join(configDir, 'config'), generateIniConfig(config))

  // 2. Scripts are auto-staged from deploy/ dir by core (01b-stage.ts)

  // 3. Warn if no backup cron registered
  const cronConfig = ctx.config.plugins?.cron as Record<string, unknown> | undefined
  const crons = (cronConfig?.crons || {}) as Record<string, unknown>
  if (!crons['backup']) {
    ctx.log.warn('[backup] plugins.backup is set, but there is no backup cron. Backups will not run on their own. Add a cron named backup under plugins.cron.crons.')
  }

  // 4. Report data
  ctx.report.data.backup = {
    destination: config.destination,
    retentionDays: config.retentionDays,
    sets: config.sets.map(s => ({
      name: s.name,
      sources: s.sources.length,
      retention: s.retainCount ? `${s.retainCount} copies` : `${s.retentionDays || config.retentionDays} days`,
    })),
  }

  ctx.log.info(`[backup] Staged ${config.sets.length} backup set(s), destination: ${config.destination}`)
}

// ── CLI commands ────────────────────────────────────────────────────────

async function backupCommand(args: string[], ctx: PluginCommandContext): Promise<void> {
  const sub = args[0] || '--help'

  if (sub === '--help' || sub === '-h') {
    console.log(`Usage: airstack fleet plugin <machine> backup <command>

Commands:
  verify     Check backup health + list archives
  run        Trigger a backup now
  download   Download latest backup to local ./backups/`)
    return
  }

  if (!ctx.remote) {
    console.error('No machine address: set host.ip in the machine file')
    process.exit(1)
  }

  const installDir = ctx.config.stack.installDir
  const appUser = ctx.config.host.appUser
  const config = parseConfig(ctx.config.plugins?.backup, installDir)
  if (!config) {
    console.error('No backup config: plugins.backup is not set for this machine')
    process.exit(1)
  }

  if (sub === 'verify') {
    // Run health check
    const healthResult = await ctx.remote.run(
      `sudo -u ${appUser} bash -c 'export STATE_DIR=${installDir}/.stack-state && ${installDir}/plugins/backup/check-health.sh'`,
    )
    const status = healthResult.stdout.trim()
    const isOk = healthResult.exitCode === 0

    console.log(`\nBackup Health: ${isOk ? '\x1b[32m' : '\x1b[31m'}${status}\x1b[0m`)

    // Show last run details
    const lastRunResult = await ctx.remote.run(
      `sudo cat ${installDir}/.stack-state/backup/last-run.json 2>/dev/null || echo '{}'`,
    )
    try {
      const lastRun = JSON.parse(lastRunResult.stdout.trim())
      if (lastRun.timestamp) {
        console.log(`Last Run: ${lastRun.timestamp}`)
        if (lastRun.sets) {
          for (const [name, set] of Object.entries(lastRun.sets as Record<string, any>)) {
            const sizeKb = set.size_bytes ? Math.round(set.size_bytes / 1024) : 0
            const statusIcon = set.status === 'ok' ? '\x1b[32m✓\x1b[0m' : set.status === 'empty' ? '\x1b[33m⚠\x1b[0m' : '\x1b[31m✗\x1b[0m'
            console.log(`  ${statusIcon} ${name}: ${set.status} ${sizeKb ? `(${sizeKb}KB)` : ''}`)
          }
        }
      }
    } catch { /* no last-run data */ }

    // List archives
    console.log(`\nArchives in ${config.destination}:`)
    const lsResult = await ctx.remote.run(
      // Glob inside sudo: the destination dir is owner-only.
      `sudo sh -c 'ls -lhS ${config.destination}/*.tar.gz' 2>/dev/null | head -20 || echo '  (none)'`,
    )
    console.log(lsResult.stdout)
  } else if (sub === 'run') {
    console.log('Triggering backup...\n')
    const result = await ctx.remote.run(
      `sudo -u ${appUser} bash -c 'export INSTALL_DIR=${installDir} CONFIG_DIR=${installDir}/.stack-config STATE_DIR=${installDir}/.stack-state && ${installDir}/plugins/backup/backup.sh'`,
    )
    process.stdout.write(result.stdout)
    if (result.stderr) process.stderr.write(result.stderr)
    process.exit(result.exitCode)
  } else if (sub === 'download') {
    const localDir = join(ctx.projectRoot, 'backups')
    mkdirSync(localDir, { recursive: true, mode: 0o700 })
    console.log(`Downloading backups from ${config.destination} to ./backups/`)
    // remote.rsync goes local→VPS; use direct rsync for VPS→local direction
    const expandedKey = ctx.ssh.keyPath.replace(/^~/, process.env.HOME || '')
    const sshCmd = `ssh -p ${ctx.ssh.port} -i '${expandedKey}' -o StrictHostKeyChecking=accept-new`
    const proc = Bun.spawn(
      // sudo rsync: archives are owner-only (umask 077 in backup.sh)
      ['rsync', '-avz', '--rsync-path=sudo rsync', '-e', sshCmd, `${ctx.ssh.user}@${ctx.ssh.host}:${config.destination}/`, `${localDir}/`],
      { stdout: 'inherit', stderr: 'inherit' },
    )
    const code = await proc.exited
    if (code === 0) {
      console.log(`\nDownloaded to: ${localDir}`)
    } else {
      console.error('Download failed')
      process.exit(code)
    }
  } else {
    console.error(`Unknown backup command: ${sub}. Run: airstack fleet plugin <machine> backup --help`)
    process.exit(1)
  }
}

// ── Registration ────────────────────────────────────────────────────────────

// Archives and pre-upgrade copies hold OAuth tokens and config: owner-only, always.
// (backup.sh already uses umask 077; this also fixes copies made by hand.)
async function postSyncHook(ctx: DeployContext, raw: unknown): Promise<void> {
  if (!ctx.remote) return
  const config = parseConfig(raw, ctx.config.stack.installDir)
  if (!config) return
  const dest = config.destination
  if (!/^\/[A-Za-z0-9_./-]+$/.test(dest)) return
  await ctx.remote.run(`sudo test -d ${dest} && sudo chmod -R go-rwx ${dest} || true`)
}

export function register(_config: unknown): Plugin {
  return {
    name: 'backup',
    scope: 'stack',
    commands: {
      backup: {
        description: 'Manage backups — verify, run, download',
        run: backupCommand,
      },
    },
    report: {
      title: 'Backups',
      order: 25,
      template: `{{#if backup.sets}}| Set | Sources | Retention |
|---|---|---|
{{#each backup.sets}}| {{this.name}} | {{this.sources}} path(s) | {{this.retention}} |
{{/each}}
**Destination:** \`{{backup.destination}}\`
{{else}}No backups configured.{{/if}}`,
    },
    hooks: {
      'pre-stage': preStageHook,
      stage: stageHook,
      'post-sync': postSyncHook,
    },
  }
}
