import { describe, it, expect, beforeEach, afterEach } from 'vitest'
import { mkdirSync, writeFileSync, rmSync, readFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'
import { loadConfig } from '../../../cli/lib/config'
import { stage } from '../../../cli/lib/stage'
import { makeTmpDir, setupProject } from '../helpers'

// ── Minimal valid stack.yml ──────────────────────────────────────────────────

const MINIMAL_STACK = `
stack:
  installDir: /home/deploy
  projectName: test-project
host:
  hostname: myhost
`

// ── Helpers ──────────────────────────────────────────────────────────────────

function makeProject(stackYml = MINIMAL_STACK, env = ''): {
  root: string
  deployDir: string
} {
  const root = setupProject(env, stackYml)
  const deployDir = join(root, '.deploy')
  return { root, deployDir }
}

// ── Tests ────────────────────────────────────────────────────────────────────

describe('stage', () => {
  let root: string
  let deployDir: string

  afterEach(() => {
    if (root) rmSync(root, { recursive: true, force: true })
  })

  it('copies deploy/ base into .deploy/', () => {
    ;({ root, deployDir } = makeProject())

    // Create a deploy/ directory with some files
    mkdirSync(join(root, 'deploy', 'conf'), { recursive: true })
    writeFileSync(join(root, 'deploy', 'conf', 'nginx.conf'), 'server {}')
    writeFileSync(join(root, 'deploy', 'setup.sh'), '#!/bin/bash')

    const config = loadConfig(root)
    stage({ projectRoot: root, sharedPaths: [], config, deployDir })

    expect(existsSync(join(deployDir, 'conf', 'nginx.conf'))).toBe(true)
    expect(readFileSync(join(deployDir, 'conf', 'nginx.conf'), 'utf8')).toBe('server {}')
    expect(existsSync(join(deployDir, 'setup.sh'))).toBe(true)
  })

  it('renders templates on top of base', () => {
    const stackYml = `
stack:
  installDir: /home/deploy
  projectName: test-project
host:
  hostname: myhost

templates:
  docker-compose.yml: templates/docker-compose.yml.hbs
`
    ;({ root, deployDir } = makeProject(stackYml))

    // Create deploy/ base with a placeholder
    mkdirSync(join(root, 'deploy'), { recursive: true })
    writeFileSync(join(root, 'deploy', 'base.txt'), 'base file')

    // Create template
    mkdirSync(join(root, 'templates'), { recursive: true })
    writeFileSync(
      join(root, 'templates', 'docker-compose.yml.hbs'),
      'project: {{stack.projectName}}',
    )

    const config = loadConfig(root)
    stage({ projectRoot: root, sharedPaths: [], config, deployDir })

    expect(existsSync(join(deployDir, 'base.txt'))).toBe(true)
    expect(readFileSync(join(deployDir, 'docker-compose.yml'), 'utf8')).toBe(
      'project: test-project',
    )
  })

  it('cleans .deploy/ before staging (stale files removed)', () => {
    ;({ root, deployDir } = makeProject())

    // Pre-populate .deploy/ with a stale file
    mkdirSync(deployDir, { recursive: true })
    writeFileSync(join(deployDir, 'stale.txt'), 'old content')

    const config = loadConfig(root)
    stage({ projectRoot: root, sharedPaths: [], config, deployDir })

    expect(existsSync(join(deployDir, 'stale.txt'))).toBe(false)
  })

  it('generates stack manifest in etc/stacks/ with PROJECT_NAME and INSTALL_DIR', () => {
    ;({ root, deployDir } = makeProject())

    const config = loadConfig(root)
    const manifestEntries: Record<string, string> = {
      PROJECT_NAME: 'test-project',
      INSTALL_DIR: '/home/deploy',
      CONFIG_DIR: '/home/deploy/.stack-config',
      STATE_DIR: '/home/deploy/.stack-state',
    }
    stage({ projectRoot: root, sharedPaths: [], config, deployDir, manifestEntries })

    const manifestPath = join(deployDir, 'etc', 'stacks', 'test-project.env')
    expect(existsSync(manifestPath)).toBe(true)

    const content = readFileSync(manifestPath, 'utf8')
    expect(content).toContain('PROJECT_NAME=test-project')
    expect(content).toContain('INSTALL_DIR=/home/deploy')
    expect(content).toContain('# Generated by airstack deploy')
  })

  it('works without deploy/ directory (just templates)', () => {
    const stackYml = `
stack:
  installDir: /opt/app
  projectName: no-deploy-dir
host:
  hostname: myhost

templates:
  config.txt: templates/config.hbs
`
    ;({ root, deployDir } = makeProject(stackYml))

    mkdirSync(join(root, 'templates'), { recursive: true })
    writeFileSync(join(root, 'templates', 'config.hbs'), 'host={{host.hostname}}')

    const config = loadConfig(root)
    stage({ projectRoot: root, sharedPaths: [], config, deployDir })

    expect(existsSync(join(deployDir, 'config.txt'))).toBe(true)
    expect(readFileSync(join(deployDir, 'config.txt'), 'utf8')).toBe('host=myhost')

    const manifestPath = join(deployDir, 'etc', 'stacks', 'no-deploy-dir.env')
    expect(existsSync(manifestPath)).toBe(true)
  })

  it('works without templates section (just deploy/ base)', () => {
    ;({ root, deployDir } = makeProject())

    mkdirSync(join(root, 'deploy'), { recursive: true })
    writeFileSync(join(root, 'deploy', 'run.sh'), '#!/bin/bash\necho hello')

    const config = loadConfig(root)
    stage({ projectRoot: root, sharedPaths: [], config, deployDir })

    expect(existsSync(join(deployDir, 'run.sh'))).toBe(true)
    expect(readFileSync(join(deployDir, 'run.sh'), 'utf8')).toBe('#!/bin/bash\necho hello')

    const manifestPath = join(deployDir, 'etc', 'stacks', 'test-project.env')
    expect(existsSync(manifestPath)).toBe(true)
  })

  it('template errors are collected (not thrown)', () => {
    const stackYml = `
stack:
  installDir: /home/deploy
  projectName: test-project
host:
  hostname: myhost

templates:
  out.txt: templates/missing.hbs
`
    ;({ root, deployDir } = makeProject(stackYml))

    const config = loadConfig(root)
    const errors: string[] = []

    expect(() =>
      stage({ projectRoot: root, sharedPaths: [], config, deployDir, errors }),
    ).not.toThrow()

    expect(errors).toHaveLength(1)
    expect(errors[0]).toMatch(/not found/i)
  })

  it('passes host, stack, and plugins as template context', () => {
    const stackYml = `
stack:
  installDir: /opt/myapp
  projectName: ctx-test
host:
  hostname: ctx-host

plugins:
  myplugin:
    value: pluginval

templates:
  out.txt: templates/ctx.hbs
`
    ;({ root, deployDir } = makeProject(stackYml))

    mkdirSync(join(root, 'templates'), { recursive: true })
    writeFileSync(
      join(root, 'templates', 'ctx.hbs'),
      'host={{host.hostname}} install={{stack.installDir}} plugin={{plugins.myplugin.value}}',
    )

    const config = loadConfig(root)
    stage({ projectRoot: root, sharedPaths: [], config, deployDir })

    const out = readFileSync(join(deployDir, 'out.txt'), 'utf8')
    expect(out).toBe('host=ctx-host install=/opt/myapp plugin=pluginval')
  })

  it('throws if deployDir is not named .deploy', () => {
    ;({ root } = makeProject())
    const config = loadConfig(root)
    const badDir = join(root, 'output')
    expect(() => stage({ projectRoot: root, sharedPaths: [], config, deployDir: badDir }))
      .toThrow(/must be named .deploy/)
  })

  it('throws if deployDir is outside projectRoot', () => {
    ;({ root } = makeProject())
    const config = loadConfig(root)
    const badDir = '/tmp/.deploy'
    expect(() => stage({ projectRoot: root, sharedPaths: [], config, deployDir: badDir }))
      .toThrow(/must be inside projectRoot/)
  })

  it('allows .deploy inside projectRoot', () => {
    ;({ root, deployDir } = makeProject())
    const config = loadConfig(root)
    expect(() => stage({ projectRoot: root, sharedPaths: [], config, deployDir }))
      .not.toThrow()
  })

  it('passes extraContext as top-level template context keys', () => {
    const stackYml = `
stack:
  installDir: /home/deploy
  projectName: extra-ctx-test
host:
  hostname: myhost

templates:
  out.txt: templates/out.hbs
`
    ;({ root, deployDir } = makeProject(stackYml))

    mkdirSync(join(root, 'templates'), { recursive: true })
    writeFileSync(
      join(root, 'templates', 'out.hbs'),
      'service={{service_name}} token={{auth_token}}',
    )

    const config = loadConfig(root)
    stage({
      projectRoot: root,
      sharedPaths: [],
      config,
      deployDir,
      extraContext: { service_name: 'my-service', auth_token: 'tok-abc' },
    })

    const out = readFileSync(join(deployDir, 'out.txt'), 'utf8')
    expect(out).toBe('service=my-service token=tok-abc')
  })

  it('camelCase stack keys are accessible in templates', () => {
    const stackYml = `
stack:
  installDir: /home/deploy
  projectName: camel-test
  egressPort: 3128
host:
  hostname: myhost

templates:
  out.txt: templates/out.hbs
`
    ;({ root, deployDir } = makeProject(stackYml))

    mkdirSync(join(root, 'templates'), { recursive: true })
    writeFileSync(
      join(root, 'templates', 'out.hbs'),
      'port={{stack.egressPort}} name={{stack.projectName}} dir={{stack.installDir}}',
    )

    const config = loadConfig(root)
    stage({ projectRoot: root, sharedPaths: [], config, deployDir })

    const out = readFileSync(join(deployDir, 'out.txt'), 'utf8')
    expect(out).toBe('port=3128 name=camel-test dir=/home/deploy')
  })

  it('camelCase keys in nested stack objects are accessible in templates', () => {
    const stackYml = `
stack:
  installDir: /home/deploy
  projectName: nested-camel-test
  egressProxy:
    authToken: secret-tok
    listenPort: 3128
host:
  hostname: myhost

templates:
  out.txt: templates/out.hbs
`
    ;({ root, deployDir } = makeProject(stackYml))

    mkdirSync(join(root, 'templates'), { recursive: true })
    writeFileSync(
      join(root, 'templates', 'out.hbs'),
      'token={{stack.egressProxy.authToken}} port={{stack.egressProxy.listenPort}}',
    )

    const config = loadConfig(root)
    stage({ projectRoot: root, sharedPaths: [], config, deployDir })

    const out = readFileSync(join(deployDir, 'out.txt'), 'utf8')
    expect(out).toBe('token=secret-tok port=3128')
  })

  it('manifest contains correct PROJECT_NAME and INSTALL_DIR values', () => {
    const stackYml = `
stack:
  installDir: /opt/my-app
  projectName: manifest-check
host:
  hostname: myhost
`
    ;({ root, deployDir } = makeProject(stackYml))

    const config = loadConfig(root)
    const manifestEntries: Record<string, string> = {
      PROJECT_NAME: 'manifest-check',
      INSTALL_DIR: '/opt/my-app',
      CONFIG_DIR: '/opt/my-app/.stack-config',
      STATE_DIR: '/opt/my-app/.stack-state',
    }
    stage({ projectRoot: root, sharedPaths: [], config, deployDir, manifestEntries })

    const manifestPath = join(deployDir, 'etc', 'stacks', 'manifest-check.env')
    expect(existsSync(manifestPath)).toBe(true)

    const content = readFileSync(manifestPath, 'utf8')
    // Exact values — not just "contains projectName somewhere"
    expect(content).toMatch(/^PROJECT_NAME=manifest-check$/m)
    expect(content).toMatch(/^INSTALL_DIR=\/opt\/my-app$/m)
  })

  it('deploy/ base is copied before templates so templates can override base files', () => {
    const stackYml = `
stack:
  installDir: /home/deploy
  projectName: override-test
host:
  hostname: myhost

templates:
  docker-compose.yml: templates/docker-compose.yml.hbs
`
    ;({ root, deployDir } = makeProject(stackYml))

    // Put a base docker-compose.yml in deploy/ that should be OVERRIDDEN by template
    mkdirSync(join(root, 'deploy'), { recursive: true })
    writeFileSync(join(root, 'deploy', 'docker-compose.yml'), 'base: content')
    writeFileSync(join(root, 'deploy', 'base-only.sh'), '#!/bin/bash')

    // Template that will overwrite docker-compose.yml
    mkdirSync(join(root, 'templates'), { recursive: true })
    writeFileSync(
      join(root, 'templates', 'docker-compose.yml.hbs'),
      'project: {{stack.projectName}}',
    )

    const config = loadConfig(root)
    stage({ projectRoot: root, sharedPaths: [], config, deployDir })

    // base-only file from deploy/ is present
    expect(existsSync(join(deployDir, 'base-only.sh'))).toBe(true)

    // docker-compose.yml is the rendered template version, not the base version
    const out = readFileSync(join(deployDir, 'docker-compose.yml'), 'utf8')
    expect(out).toBe('project: override-test')
    expect(out).not.toBe('base: content')
  })

  it('throws if deployDir basename is not .deploy', () => {
    ;({ root } = makeProject())
    const config = loadConfig(root)
    const badDir = join(root, 'not-deploy')
    expect(() => stage({ projectRoot: root, sharedPaths: [], config, deployDir: badDir }))
      .toThrow(/must be named .deploy/)
  })

  it('throws if deployDir is outside projectRoot (path traversal)', () => {
    ;({ root } = makeProject())
    const config = loadConfig(root)
    // A .deploy dir that is valid name but outside this project's root
    const outsideDir = join(root, '..', 'some-other-dir', '.deploy')
    expect(() => stage({ projectRoot: root, sharedPaths: [], config, deployDir: outsideDir }))
      .toThrow(/must be inside projectRoot/)
  })
})
