#!/bin/bash
set -euo pipefail
# harden.sh — UFW, SSH hardening, swap, fail2ban, sysctl, unattended-upgrades.
# From: Playbook 02, steps 2.3, 2.4, 2.5
#
# Two-phase operation:
#   Phase 1 (default): Sets up hardened SSH port alongside port 22, configures
#     all security. Port 22 stays open as safety net.
#   Phase 2 (FINALIZE=true): Closes port 22, restricts AllowUsers.
#
# Required env:
#   SSH_PORT             Current SSH port (default: 22)
#   SSH_HARDENED_PORT    Target hardened SSH port
#   SUDO_USER            Admin user for AllowUsers (default: admin)
#
# Optional env:
#   SSH_CURRENT_USER     Current SSH user to keep during transition (default: root)
#   SWAP_SIZE            Swap file size (default: 8G)
#   FINALIZE             If "true", run phase 2 (close port 22)
#
# Output: SETUP_HARDEN_OK or SETUP_HARDEN_FINALIZE_OK

CURRENT_STEP=""
trap 'if [ $? -ne 0 ]; then echo "FAILED during: ${CURRENT_STEP:-unknown step}" >&2; fi' EXIT

SSH_PORT="${SSH_PORT:-22}"
SUDO_USER="${SUDO_USER:-admin}"
SSH_CURRENT_USER="${SSH_CURRENT_USER:-root}"
SWAP_SIZE="${SWAP_SIZE:-8G}"
FINALIZE="${FINALIZE:-false}"

if [ -z "${SSH_HARDENED_PORT:-}" ]; then
  echo "ERROR: SSH_HARDENED_PORT is required" >&2
  exit 1
fi

# ── Phase 2: Finalize ───────────────────────────────────────────────────────

if [ "${FINALIZE}" = "true" ]; then
  echo "==> Finalizing SSH hardening (closing port 22)..."

  # Update socket to hardened port only
  CURRENT_STEP="socket override (finalize)"
  mkdir -p /etc/systemd/system/ssh.socket.d
  cat > /etc/systemd/system/ssh.socket.d/override.conf << EOF
[Socket]
ListenStream=
ListenStream=0.0.0.0:${SSH_HARDENED_PORT}
ListenStream=[::]:${SSH_HARDENED_PORT}
EOF

  # Restrict AllowUsers to admin only
  CURRENT_STEP="SSH AllowUsers (finalize)"
  if [ -f /etc/ssh/sshd_config.d/hardening.conf ]; then
    sed -i "s/^AllowUsers .*/AllowUsers ${SUDO_USER}/" /etc/ssh/sshd_config.d/hardening.conf
  fi

  # Apply
  CURRENT_STEP="restart ssh.socket (finalize)"
  systemctl daemon-reload
  systemctl restart ssh.socket

  # Remove port 22 from UFW
  CURRENT_STEP="UFW remove port 22"
  ufw delete allow 22/tcp 2>/dev/null || true

  # Verify port 22 is no longer listening
  if ss -tlnp | grep -q ':22 '; then
    echo "WARNING: Port 22 still appears to be listening" >&2
  else
    echo "  Port 22 closed"
  fi

  echo "  AllowUsers restricted to: ${SUDO_USER}"
  echo ""
  echo "SSH hardening finalized."
  echo "SETUP_HARDEN_FINALIZE_OK"
  exit 0
fi

# ── Phase 1: Full hardening with port 22 safety net ──────────────────────────

# ── 1. UFW Firewall ─────────────────────────────────────────────────────────

CURRENT_STEP="UFW firewall"
echo "==> Configuring UFW firewall..."

ufw default deny incoming
ufw default allow outgoing

# Keep port 22 during transition + add hardened port
ufw allow 22/tcp
ufw allow "${SSH_HARDENED_PORT}/tcp"

# Enable (--force skips interactive prompt)
ufw --force enable

echo "  UFW active: ports 22 and ${SSH_HARDENED_PORT} allowed"

# ── 2. SSH Hardening ────────────────────────────────────────────────────────

CURRENT_STEP="SSH config backup"
echo "==> Configuring SSH hardening..."

# Backup original if not already backed up
if [ ! -f /etc/ssh/sshd_config.backup ]; then
  cp /etc/ssh/sshd_config /etc/ssh/sshd_config.backup
fi

# Write hardened SSH config
CURRENT_STEP="SSH hardening.conf"
cat > /etc/ssh/sshd_config.d/hardening.conf << EOF
# Hardened SSH config — generated by vps-setup harden
Port ${SSH_HARDENED_PORT}

# Disable root login
PermitRootLogin no

# Key-only authentication
PasswordAuthentication no
ChallengeResponseAuthentication no
KbdInteractiveAuthentication no

# Required on Ubuntu for proper auth
UsePAM yes

# Allow admin + current user during transition (finalized later)
AllowUsers ${SUDO_USER} ${SSH_CURRENT_USER}

# Connection limits
MaxAuthTries 3
MaxSessions 3
LoginGraceTime 30

# Disable unused features
X11Forwarding no
AllowTcpForwarding no
AllowAgentForwarding no
PermitEmptyPasswords no
PermitUserEnvironment no

# Strong algorithms only
KexAlgorithms sntrup761x25519-sha512@openssh.com,curve25519-sha256@libssh.org,diffie-hellman-group16-sha512
Ciphers chacha20-poly1305@openssh.com,aes256-gcm@openssh.com
MACs hmac-sha2-512-etm@openssh.com,hmac-sha2-256-etm@openssh.com
EOF

# Systemd socket override — listen on BOTH ports during transition
CURRENT_STEP="SSH socket override"
mkdir -p /etc/systemd/system/ssh.socket.d
cat > /etc/systemd/system/ssh.socket.d/override.conf << EOF
[Socket]
ListenStream=
ListenStream=0.0.0.0:22
ListenStream=[::]:22
ListenStream=0.0.0.0:${SSH_HARDENED_PORT}
ListenStream=[::]:${SSH_HARDENED_PORT}
EOF

# Validate config before applying
CURRENT_STEP="SSH config validation"
if ! sshd -t; then
  echo "ERROR: SSH config validation failed! Reverting..." >&2
  rm -f /etc/ssh/sshd_config.d/hardening.conf
  rm -rf /etc/systemd/system/ssh.socket.d
  echo "Config reverted. Fix issues and retry." >&2
  exit 1
fi
echo "  SSH config validated"

# Apply — ONLY restart socket, NEVER ssh.service
CURRENT_STEP="restart ssh.socket"
systemctl daemon-reload
systemctl restart ssh.socket

# Verify hardened port is listening
CURRENT_STEP="verify SSH ports"
if ! ss -tlnp | grep -q ":${SSH_HARDENED_PORT} "; then
  echo "ERROR: Port ${SSH_HARDENED_PORT} not listening after restart" >&2
  exit 1
fi
echo "  SSH listening on ports 22 and ${SSH_HARDENED_PORT}"

# ── 3. Swap ─────────────────────────────────────────────────────────────────

CURRENT_STEP="swap configuration (${SWAP_SIZE})"
echo "==> Configuring swap (${SWAP_SIZE})..."

if swapon --show | grep -q /swapfile; then
  echo "  Swap already active, skipping creation"
else
  fallocate -l "${SWAP_SIZE}" /swapfile
  chmod 600 /swapfile
  mkswap /swapfile
  swapon /swapfile

  # Persist across reboots
  grep -q '/swapfile' /etc/fstab || \
    echo '/swapfile none swap sw 0 0' >> /etc/fstab
fi

# Low swappiness: prefer RAM, only swap under pressure
sysctl -w vm.swappiness=10 > /dev/null
echo 'vm.swappiness=10' > /etc/sysctl.d/99-swap.conf

if ! swapon --show --noheadings | grep -q /swapfile; then
  echo "ERROR: Swap not active after setup" >&2
  exit 1
fi
echo "  Swap: $(swapon --show --noheadings | awk '{print $3}')"

# ── 4. Fail2ban ──────────────────────────────────────────────────────────────

CURRENT_STEP="fail2ban (port ${SSH_HARDENED_PORT})"
echo "==> Configuring fail2ban (SSH port ${SSH_HARDENED_PORT})..."

cat > /etc/fail2ban/jail.local << EOF
[DEFAULT]
bantime = 1h
findtime = 10m
maxretry = 5
backend = systemd

[sshd]
enabled = true
port = ${SSH_HARDENED_PORT}
filter = sshd
logpath = /var/log/auth.log
maxretry = 3
bantime = 24h
EOF

systemctl enable fail2ban
systemctl restart fail2ban

if ! systemctl is-active --quiet fail2ban; then
  echo "ERROR: fail2ban failed to start" >&2
  exit 1
fi
echo "  fail2ban active, SSH jail on port ${SSH_HARDENED_PORT}"

# ── 5. Unattended Upgrades ──────────────────────────────────────────────────

CURRENT_STEP="unattended-upgrades"
echo "==> Configuring unattended-upgrades..."

apt install -y unattended-upgrades

cat > /etc/apt/apt.conf.d/50unattended-upgrades << 'EOF'
Unattended-Upgrade::Allowed-Origins {
    "${distro_id}:${distro_codename}";
    "${distro_id}:${distro_codename}-security";
    "${distro_id}ESMApps:${distro_codename}-apps-security";
    "${distro_id}ESM:${distro_codename}-infra-security";
};
Unattended-Upgrade::AutoFixInterruptedDpkg "true";
Unattended-Upgrade::Remove-Unused-Kernel-Packages "true";
Unattended-Upgrade::Remove-Unused-Dependencies "true";
Unattended-Upgrade::Automatic-Reboot "false";
EOF

systemctl enable unattended-upgrades
echo "  Unattended security upgrades enabled"

# ── 6. Kernel Hardening (sysctl) ────────────────────────────────────────────

CURRENT_STEP="kernel hardening (sysctl)"
echo "==> Applying kernel hardening..."

cat > /etc/sysctl.d/99-security.conf << 'EOF'
# IP Spoofing protection
net.ipv4.conf.all.rp_filter = 1
net.ipv4.conf.default.rp_filter = 1

# Ignore ICMP broadcast requests
net.ipv4.icmp_echo_ignore_broadcasts = 1

# Disable source packet routing
net.ipv4.conf.all.accept_source_route = 0
net.ipv4.conf.default.accept_source_route = 0

# Ignore send redirects
net.ipv4.conf.all.send_redirects = 0
net.ipv4.conf.default.send_redirects = 0

# Block SYN attacks
net.ipv4.tcp_syncookies = 1
net.ipv4.tcp_max_syn_backlog = 2048
net.ipv4.tcp_synack_retries = 2

# Log Martians
net.ipv4.conf.all.log_martians = 1

# Ignore ICMP redirects
net.ipv4.conf.all.accept_redirects = 0
net.ipv4.conf.default.accept_redirects = 0

# Enable ASLR
kernel.randomize_va_space = 2

# Restrict dmesg access
kernel.dmesg_restrict = 1

# Restrict kernel pointer access
kernel.kptr_restrict = 2
EOF

sysctl -p /etc/sysctl.d/99-security.conf

if [ "$(sysctl -n net.ipv4.tcp_syncookies)" != "1" ]; then
  echo "ERROR: Kernel sysctl parameters not applied" >&2
  exit 1
fi
echo "  Kernel parameters applied"

# ── Done ─────────────────────────────────────────────────────────────────────

CURRENT_STEP=""
echo ""
echo "System hardening complete."
echo ""
echo "IMPORTANT: Test SSH on the hardened port from your LOCAL machine:"
echo "  ssh -i <key> -p ${SSH_HARDENED_PORT} ${SUDO_USER}@<vps-ip>"
echo ""
echo "If it works, update .env (SSH_USER=${SUDO_USER}, SSH_PORT=${SSH_HARDENED_PORT})"
echo "then run: stack-cli vps-setup harden --finalize"
echo ""
echo "SETUP_HARDEN_OK"
